# 校验
n_lines = sum(len(s['l']) for s in SONGS)
cats_used = sorted(set(s['c'] for s in SONGS))
assert cats_used == sorted(CATS), cats_used
titles = [s['n'] for s in SONGS]
assert len(set(titles)) == len(titles), '标题重复'
# 英文残留检查（歌词行；melody 里的音名是合法英文，单独跳过）
import re
for s in SONGS:
    for line in [s['n']] + s['l']:
        assert not re.search(r'[A-Za-z]', line), line
    if 'm' in s:
        assert len(s['m']) == len(s['l']), '%s 旋律 %d 句 != 歌词 %d 句' % (s['n'], len(s['m']), len(s['l']))
        for mline in s['m']:
            for tok in mline.split():
                assert re.match(r'^[A-G]#?[3-5](:[0-9.]+)?$', tok), '%s 音符非法: %s' % (s['n'], tok)
# id 顺序变化检查：已存在的音频 id 不允许被重排（防止插队导致音频错位）
old_ids = []
if os.path.exists(os.path.join(BASE, 'data.js')):
    with io.open(os.path.join(BASE, 'data.js'), encoding='utf-8') as f:
        src = f.read()
    if 'window.NURSERY_DATA' in src:
        old = json.loads(src.split('window.NURSERY_DATA = ', 1)[1].rstrip().rstrip(';'))
        old_ids = [x['id'] + ':' + x['title'] for x in old]
new_ids = ['n%03d:%s' % (i, s['n']) for i, s in enumerate(SONGS, 1)]
if old_ids:
    overlap = [x for x in old_ids if x in new_ids]
    for i, oid in enumerate(overlap):
        assert oid == new_ids[i], 'id 重排！%s 位置变化' % oid

data = []
for i, s in enumerate(SONGS, 1):
    d = {'id': 'n%03d' % i, 'title': s['n'], 'cat': s['c'], 'lines': s['l']}
    if 'm' in s:
        d['melody'] = s['m']
        d['bpm'] = s.get('bpm', 96)
    data.append(d)

meta = {'total': len(data), 'cats': CATS, 'singable': sum(1 for d in data if 'melody' in d)}

with io.open(os.path.join(BASE, 'data.js'), 'w', encoding='utf-8') as f:
    f.write('window.NURSERY_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
    f.write('window.NURSERY_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')

print('儿歌 %d 首，歌词 %d 行，音频共 %d 段' % (len(data), n_lines, n_lines + len(data)))
print('分类:', {c: sum(1 for s in SONGS if s['c'] == c) for c in CATS})
print('可跟唱:', meta['singable'], '首 ->', [d['title'] for d in data if 'melody' in d])
